def run_plain(body):
    return deobfuscate(BANNER + body.encode(), Options(sandbox_timeout=30))


def test_every_way_of_looping_over_a_roblox_list_is_seen():
    r = run_plain('''
for _, v in ipairs(workspace:GetChildren()) do v:Destroy() end
for _, p in pairs(game:GetService("Players"):GetPlayers()) do p.Character:Destroy() end
for _, d in workspace:GetDescendants() do d:Destroy() end
for _, d in next, workspace:GetDescendants() do d:Destroy() end
''')
    t = r.text
    assert 'for _, child in ipairs(workspace:GetChildren()) do\n\tchild:Destroy()\nend' in t
    assert 'for _, player in ipairs(game:GetService("Players"):GetPlayers()) do\n\tplayer.Character:Destroy()\nend' in t
    assert t.count('for _, descendant in ipairs(workspace:GetDescendants()) do') == 2
    assert r.info['syntax_ok'] is True


def test_the_script_sees_only_the_fake_environment_not_the_harness():
    # names the harness uses internally must stay free for the script: `fmt`, `emit`, `env`, `proxies`, `mk` ...
    r = run_plain('''
fmt, emit, env, proxies, mk = 1, 2, 3, 4, 5
print(fmt + emit + env + proxies + mk)
print(type(ipairs), typeof(game))
''')
    assert 'print(15)' in r.text and 'print("function", "Instance")' in r.text


def test_functions_of_the_environment_keep_their_names_and_are_not_run_as_callbacks():
    r = run_plain('''
task.delay(1, print, "x")
workspace.ChildAdded:Connect(print)
game:GetService("Players").PlayerAdded:Connect(function(p) print("hi", p.Name) end)
''')
    t = r.text
    assert 'task.delay(1, print, "x")' in t and 'workspace.ChildAdded:Connect(print)' in t
    assert t.count('print("x")') == 0 and 'function(inst)\n\tprint("hi", inst.Name)\nend' in t.replace('\n\t\t', '\n\t')
    assert r.info['syntax_ok'] is True


def test_argument_lists_never_end_in_a_comma_and_strings_keep_the_values_glued_into_them():
    r = run_plain('''
local P = game:GetService("Players").LocalPlayer
task.delay(2, function() print("later") end, 5)
local lbl = Instance.new("TextLabel")
lbl.Text = "Hi " .. P.Name
print(Vector3.new(1, 2, 3) * 2)
''')
    t = r.text
    assert 'task.delay(2, function()\n\tprint("later")\nend, 5)' in t
    assert 'Instance.new("TextLabel").Text = "Hi {game:GetService(\\"Players\\").LocalPlayer.Name}"' in t
    assert 'print((Vector3.new(1, 2, 3) * 2))' in t
    assert r.info['syntax_ok'] is True


def test_output_is_valid_luau(result):
    ok, msg, _ = compile_check(result.text)
    assert ok, msg


def test_a_script_that_calls_nothing_is_refused_with_the_reason():
    with pytest.raises(EngineError) as e:
        deobfuscate(BANNER + b'local x = 1 + 1\nerror("boom")\n', Options(sandbox_timeout=30))
    assert e.value.code == 'unsupported' and 'nothing observable' in e.value.message and 'boom' in e.value.message


def test_a_busy_loop_hits_the_time_limit():
    with pytest.raises(EngineError) as e:
        deobfuscate(BANNER + b'while true do end\n', Options(sandbox_timeout=1))
    assert e.value.code == 'timeout'


def test_broken_script_is_a_syntax_error():
    with pytest.raises(EngineError) as e:
        deobfuscate(BANNER + b'local x = = 3 end end\n', Options(sandbox_timeout=30))
    assert e.value.code == 'syntax'


def test_the_script_cannot_reach_the_real_globals():
    # getfenv/setfenv are replaced: whatever level is asked for, the fake environment comes back; there is no os.execute
    src = BANNER + b'''
    local env = getfenv()
    print(type(env.os.execute), type(env.dofile))
    print(getfenv(0) == env, rawequal(getfenv(1), env))
    '''
    r = deobfuscate(src, Options(sandbox_timeout=30))
    assert 'print("nil", "table")' in r.text and 'print(true, true)' in r.text


# ---------------------------------------------------------------------------------------------- the renderer alone
def render(log):
    r = Renderer(parse(log.replace('\\t', '\t')))
    return r.render()


def test_single_use_results_are_inlined_and_reused_ones_get_names():
    log = '\n'.join([
        'B\\tM\\tkind=main',
        'C\\t1\\tgame:GetService\\t"Players"',
        'C\\t2\\t@R1.LocalPlayer:WaitForChild\\t"PlayerGui"',
        'C\\t3\\t@R2:FindFirstChild\\t"X"',
        'C\\t4\\t@R3:Destroy\\t',
        'C\\t5\\t@R2:FindFirstChild\\t"Y"',
        'E\\tM\\tok',
        'T\\tdone'])
    assert render(log) == '\n'.join([
        'local playerGui = game:GetService("Players").LocalPlayer:WaitForChild("PlayerGui")',
        'playerGui:FindFirstChild("X"):Destroy()',
        'playerGui:FindFirstChild("Y")'])


def test_a_callback_that_uses_its_own_connection_declares_it_first():
    log = '\n'.join([
        'B\\tM\\tkind=main',
        'C\\t1\\tgame:GetService("RunService").Heartbeat:Connect\\t@F1',
        'C\\t2\\t@R1:Disconnect\\t',
        'E\\tM\\tok',
        'B\\tF1\\tkind=frame;param=dt;dist=near',
        'C\\t3\\t@R1:Disconnect\\t',
        'E\\tF1\\tok'])
    out = render(log)
    assert out.startswith('local connection\nconnection = game:GetService("RunService").Heartbeat:Connect(function(dt)')
    assert '\tconnection:Disconnect()\nend)' in out


def test_toggle_branches_and_unrun_functions():
    log = '\n'.join([
        'B\\tM\\tkind=main',
        'C\\t1\\tlib:AddToggle\\t{text = "T", callback = @F1}',
        'C\\t2\\tlib:AddButton\\t{callback = @F2}',
        'E\\tM\\tok',
        'B\\tF1\\tkind=toggle;param=enabled;val=true;dist=near',
        'C\\t3\\tprint\\t"on"',
        'E\\tF1\\tok',
        'B\\tF1\\tkind=toggle;param=enabled;val=false;dist=near',
        'E\\tF1\\tok'])
    out = render(log)
    assert 'callback = function(enabled)\n\t\tif enabled then\n\t\t\tprint("on")\n\t\tend\n\tend,' in out
    assert 'callback = function() end --[[not run in the trace]],' in out


def test_loop_over_a_fake_list_gets_an_unknown_marker_when_empty():
    log = '\n'.join(['B\\tM\\tkind=main', 'C\\t1\\tworkspace:GetChildren\\t', 'I\\t1\\t@R1', 'X\\t1', 'E\\tM\\tok'])
    out = render(log)
    assert out == ('for _, child in ipairs(workspace:GetChildren()) do\n'
                   '\t-- UNKNOWN: nothing observable was done with each item\nend')


def test_a_cut_thread_says_so():
    log = '\n'.join(['B\\tM\\tkind=main', 'C\\t1\\tprint\\t"a"', 'E\\tM\\tcut'])
    assert render(log).endswith('-- (trace cut here: the sandbox stopped waiting; the real script continues)')
    log = '\n'.join(['B\\tM\\tkind=main', 'C\\t1\\tprint\\t"a"', 'E\\tM\\terr:attempt to index nil'])
    assert render(log).endswith('-- STOPPED in the sandbox: attempt to index nil (usually because of the fake objects)')


def test_log_parser_survives_a_truncated_log():
    t = parse('B\tM\tkind=main\nC\t1\tprint\t"a"\nC\t2')
    assert t.main is not None and t.main.status == 'cut' and len(t.main.events) == 2


# ---------------------------------------------------------------------------------------------- front ends
INFO = dict(kind='moonveil', trace_only=True, moonveil={'version': '2.1.1'}, lines=40, calls=120, threads=5,
            downloads=['https://example.com/a.lua'], warnings=[], syntax_ok=True)


def test_verdict_never_calls_a_trace_a_decompilation():
    lines = verdict(INFO)
    text = '\n'.join(lines)
    assert lines[0] == 'Detected: MoonVeil 2.1.1 (private VM protector)'
    assert 'NOT the original source' in text and '120 calls seen in 5 threads/callbacks, 40 output lines' in text
    assert 'https://example.com/a.lua' in text and 'not fetched' in text and 'Output syntax is valid' in text
    assert 'Bytecode' not in text and 'functions,' not in text


def test_cli_names_the_result_reconstructed(monkeypatch, tmp_path, capsys):
    src = tmp_path / 'hub.lua'
    src.write_bytes(b'x')
    monkeypatch.setattr(M, 'run', lambda data, opts, hard_timeout=240, progress=None, cancel=None:
                        Result('print("t")\n', dict(INFO)))
    assert M.main([str(src)]) == 0
    assert (tmp_path / 'hub_reconstructed.lua').read_text() == 'print("t")\n'
    assert not (tmp_path / 'hub_deobf.lua').exists()
    assert 'NOT the original source' in capsys.readouterr().out


def test_folder_runs_do_not_pick_up_reconstructions_again(tmp_path):
    for n in ('a.lua', 'a_reconstructed.lua', 'b_deobf.lua'):
        (tmp_path / n).write_bytes(b'x')
    files, problems = M.expand_inputs([str(tmp_path)])
    assert [f.split('/')[-1].split('\\')[-1] for f in files] == ['a.lua'] and not problems
